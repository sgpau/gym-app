// Recorrido completo a tamaño iPhone con capturas: node scripts/e2e.mjs <url> <carpeta-capturas>
import { chromium } from 'playwright'

const [url, out] = process.argv.slice(2)
const browser = await chromium.launch()
const errors = []

async function run(name, { colorScheme = 'light', locale = 'es-ES' } = {}) {
  const context = await browser.newContext({
    viewport: { width: 393, height: 852 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme, locale, permissions: ['clipboard-read', 'clipboard-write'],
  })
  const page = await context.newPage()
  page.on('pageerror', (e) => errors.push(`${name}: ${e.message}`))
  page.on('console', (m) => { if (m.type() === 'error') errors.push(`${name}: ${m.text()}`) })
  const shot = (step) => page.screenshot({ path: `${out}/${name}-${step}.png` })
  const tap = (selector) => page.locator(`${selector} >> visible=true`).first().click()

  await page.goto(url)
  await page.waitForSelector('.tabbar')
  await page.waitForTimeout(500)
  await shot('00-today-empty')

  // Hoy: tocar una rutina de «Esta semana» la pone para hoy
  await page.locator('button.row:visible', { hasText: 'Tren inferior 1' }).click()
  await page.waitForTimeout(300)
  if (!(await page.locator('.card h2:visible').innerText()).includes('Tren inferior 1')) errors.push(`${name}: elegir rutina no cambia la tarjeta`)
  await shot('00b-today-picked')

  // Editar: arrastrar la última rutina al principio
  await page.locator('.bar-button:visible', { hasText: /Editar|Edita/ }).click()
  await page.waitForTimeout(500)
  const handles = page.locator('.drag-handle:visible')
  const from = await handles.last().boundingBox()
  const to = await handles.first().boundingBox()
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  for (let i = 1; i <= 10; i++) await page.mouse.move(from.x + from.width / 2, from.y + (to.y - from.y - 20) * i / 10)
  await page.mouse.up()
  await page.waitForTimeout(400)
  await shot('00c-plan-dragged')
  await page.locator('.navbar-side:not(.end) .bar-button:visible').last().click()
  await page.waitForTimeout(500)
  const firstRow = await page.locator('.section:visible button.row, .section:visible .row').first().innerText()
  if (!firstRow.includes('Tren inferior 2')) errors.push(`${name}: arrastrar no cambia el orden (${firstRow})`)
  await shot('00d-today-reordered')
  await tap('.tab:nth-child(2)')
  await page.waitForTimeout(300)
  await shot('01-calendar-empty')

  // Pestaña Ajustes → restaurar por defecto (ya está todo) → 7 toques en Versión → cargar datos de prueba
  await page.locator('.tab').nth(5).click()
  await page.waitForTimeout(400)
  await shot('02-settings')
  await page.locator('.swatch[aria-label="Rosa Barbie"]').click()
  await page.waitForTimeout(200)
  const accent = await page.evaluate(() => document.documentElement.style.getPropertyValue('--accent'))
  if (!['#E0218A', '#FF4FB0'].includes(accent)) errors.push(`${name}: Rosa Barbie no cambia el color (${accent})`)
  await shot('02a-settings-barbie')
  await page.locator('button.row:visible', { hasText: /Restaurar/ }).click()
  await page.waitForSelector('.alert-box')
  await shot('02b-defaults-already-there')
  await page.locator('.alert-box button').click()
  const version = page.locator('button.row:visible', { hasText: /Versi/ })
  for (let i = 0; i < 7; i++) await version.click()
  await shot('02c-settings-dev')
  await page.locator('button.row:visible', { hasText: /prueba|prova/ }).click()
  await page.waitForSelector('.alert-box', { timeout: 10000 })
  await shot('03-imported')
  await page.locator('.alert-box button').click()
  await page.locator('.tab').nth(1).click()
  await page.waitForTimeout(600)
  await shot('04-calendar-data')

  // Registrar un entreno de la rutina Tren superior 1 hoy, subir el peso del press y finalizar
  await tap('.primary-button')
  await page.waitForTimeout(500)
  await page.locator('.sheet button.row', { hasText: /Tren superior 1/ }).click()
  await page.waitForTimeout(600)
  await shot('05-editor')
  // Una recarga (actualización de la app) vuelve a abrir el entreno
  await page.reload()
  await page.waitForSelector('.tabbar')
  await page.waitForTimeout(1200)
  if (!(await page.locator('.sheet .navbar-title', { hasText: /Tren superior 1/ }).count())) errors.push(`${name}: el entreno no se reabre tras recargar`)
  // Reordenar ejercicios arrastrando: el 2.º pasa arriba y vuelve
  const exerciseNames = () => page.locator('.sheet .entry .section-header').evaluateAll((els) => els.map((e) => e.innerText.split('\n')[0]))
  const dragHandle = async (handles, from, to, extra) => {
    const a = await handles.nth(from).boundingBox()
    const b = await handles.nth(to).boundingBox()
    await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
    await page.mouse.down()
    for (let i = 1; i <= 12; i++) await page.mouse.move(a.x + a.width / 2, a.y + (b.y - a.y + extra) * i / 12)
    await page.mouse.up()
    await page.waitForTimeout(500)
  }
  const exerciseHandles = page.locator('.sheet .section-header .drag-handle')
  const before = await exerciseNames()
  await dragHandle(exerciseHandles, 1, 0, -60)
  const after = await exerciseNames()
  if (after[0] !== before[1] || after[1] !== before[0]) errors.push(`${name}: arrastrar ejercicios no cambia el orden (${after.slice(0, 2)})`)
  await shot('05a-editor-reordered')
  await dragHandle(exerciseHandles, 1, 0, -60)
  // Reordenar series arrastrando: la 3.ª pasa a ser la 1.ª
  const firstEntry = page.locator('.sheet .entry').first()
  const setWeights = firstEntry.locator('input[inputmode="decimal"]')
  const weightsBefore = await setWeights.evaluateAll((els) => els.map((e) => e.value))
  for (let i = 0; i < 3; i++) await setWeights.nth(i).fill(String(10 * (i + 1)))
  await page.locator('.sheet .navbar-title').first().click()
  await dragHandle(firstEntry.locator('.list .drag-handle'), 2, 0, -10)
  const weightsAfter = await setWeights.evaluateAll((els) => els.slice(0, 3).map((e) => e.value))
  if (weightsAfter.join() !== '30,10,20') errors.push(`${name}: arrastrar series no cambia el orden (${weightsAfter})`)
  for (let i = 0; i < 3; i++) await setWeights.nth(i).fill(weightsBefore[i] ?? '')
  await page.locator('.sheet .navbar-title').first().click()
  const weight = page.locator('.sheet input[inputmode="decimal"]')
  const current = await weight.first().inputValue()
  const heavier = String(parseFloat(current.replace(',', '.')) + 5).replace('.', ',')
  for (let i = 0; i < 3; i++) { await weight.nth(i).fill(heavier) }
  // Crear un ejercicio que no existe sin salir del entreno: queda marcado y se añade
  await page.locator('.sheet button.row:visible', { hasText: /Añadir ejercicio|Afegir exercici/ }).click()
  await page.waitForTimeout(500)
  await page.locator('.sheet input[type="search"]:visible').fill('Zancada lateral')
  await page.waitForTimeout(200)
  await shot('05c-picker-create')
  await page.locator('.sheet button.row:visible', { hasText: /Crear «Zancada lateral»/ }).click()
  await page.waitForTimeout(500)
  if ((await page.locator('.sheet input[type="text"]:visible').inputValue()) !== 'Zancada lateral') errors.push(`${name}: el nombre buscado no pasa al ejercicio nuevo`)
  await page.locator('.sheet .bar-button.bold:visible', { hasText: /Guardar|Desar/ }).click()
  await page.waitForTimeout(500)
  if (!(await page.locator('.sheet button.row:visible', { hasText: 'Zancada lateral' }).locator('.accent').count())) errors.push(`${name}: el ejercicio creado no queda marcado`)
  await shot('05d-picker-created')
  await page.locator('.sheet .bar-button.bold:visible', { hasText: /\(1\)|1/ }).click()
  await page.waitForTimeout(500)
  if (!(await exerciseNames()).includes('Zancada lateral')) errors.push(`${name}: el ejercicio creado no se añade al entreno`)
  if (await page.locator('.sheet .entry .section-header .num:visible').count()) errors.push(`${name}: sigue saliendo «Última vez» en el entreno`)
  // Minimizar el entreno, ir a otra pestaña y volver
  await page.locator('.sheet .bar-button:visible[aria-label="Minimizar"], .sheet .bar-button:visible[aria-label="Minimitzar"]').click()
  await page.waitForTimeout(400)
  if (await page.locator('.sheet:visible').count()) errors.push(`${name}: minimizar no oculta el entreno`)
  await page.locator('.tab').nth(3).click()
  await page.waitForTimeout(400)
  if (!(await page.locator('button.row:visible', { hasText: 'Zancada lateral' }).count())) errors.push(`${name}: la pestaña Ejercicios no se ve con el entreno minimizado`)
  await shot('05e-minimized')
  await page.locator('.tab').nth(1).click()
  await page.waitForTimeout(300)
  // Abrirlo desde el calendario vuelve al mismo entreno, no abre otro
  await page.locator('.card button:visible', { hasText: /Tren superior 1/ }).first().click()
  await page.waitForTimeout(400)
  if ((await page.locator('.sheet:visible').count()) !== 1) errors.push(`${name}: abrir el entreno minimizado abre otra hoja`)
  await page.locator('.sheet .bar-button:visible[aria-label="Minimizar"], .sheet .bar-button:visible[aria-label="Minimitzar"]').click()
  await page.waitForTimeout(300)
  await page.locator('.mini-bar').click()
  await page.waitForTimeout(400)
  if (!(await page.locator('.sheet:visible .navbar-title', { hasText: /Tren superior 1/ }).count())) errors.push(`${name}: la barra no vuelve al entreno`)
  if (await page.locator('.mini-bar').count()) errors.push(`${name}: la barra sigue tras volver al entreno`)
  // Las repeticiones se anotan serie a serie y pueden ser distintas
  const reps = page.locator('.sheet input[inputmode="numeric"]')
  for (let i = 0; i < await reps.count(); i++) await reps.nth(i).fill(String([10, 9, 8, 8][i % 4]))
  await shot('05b-editor-reps')
  await page.locator('.sheet:visible .bar-button.prominent').click()
  await page.waitForTimeout(800)
  await shot('06-summary')
  // Copiar entreno: series, reps y pesos al portapapeles (para pegar en Strava)
  await page.locator('.sheet .primary-button:visible', { hasText: /Copiar/ }).click()
  await page.waitForTimeout(200)
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  if (!/^Tren superior 1 · .+\n.+: .+ × 10, .+ × 9/.test(copied)) errors.push(`${name}: texto copiado inesperado: ${copied}`)
  if (!(await page.locator('.sheet .primary-button:visible', { hasText: /✓/ }).count())) errors.push(`${name}: el botón no muestra «Copiado»`)
  await shot('06a-summary-copied')
  await page.locator('.sheet .screen').last().evaluate((el) => el.scrollTo(0, 900))
  await page.waitForTimeout(300)
  await shot('07-summary-scrolled')
  await page.locator('.sheet .bar-button.prominent').last().click()
  await page.waitForTimeout(600)

  // Progreso → Press de banca
  await page.locator('.tab').nth(4).click()
  await page.waitForTimeout(400)
  await shot('08-progress-list')
  await page.locator('button.row:visible', { hasText: /Press de banca/ }).first().click()
  await page.waitForTimeout(600)
  await shot('09-progress-detail')

  // Rutinas y ejercicios
  await page.locator('.tab').nth(2).click()
  await page.waitForTimeout(300)
  await shot('10-routines')
  await page.locator('.tab').nth(3).click()
  await page.waitForTimeout(300)
  await shot('11-exercises')

  // La barra con 6 pestañas en una pantalla estrecha (iPhone SE)
  await page.setViewportSize({ width: 320, height: 568 })
  await page.waitForTimeout(300)
  await shot('12-tabbar-320')
  await context.close()
}

await run('es-light')
await run('ca-dark', { colorScheme: 'dark', locale: 'ca-ES' })
await browser.close()
console.log(errors.length ? `ERRORES:\n${errors.join('\n')}` : 'Sin errores en consola')
